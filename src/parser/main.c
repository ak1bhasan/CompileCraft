/* ==============================================================================
 * CompileCraft - LALR(1) Syntax Analyzer Standalone Driver
 * Milestone 3.3: Parser Hardening Driver
 * ============================================================================== */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* 1. Canonical header inclusion order: Bison parser header first */
#include "parser.tab.h"

/* 2. Lexer definitions and helper utilities */
#include "tokens.h"

/* 3. Parser driver interface */
#include "parser.h"

/* ==============================================================================
 * Compile-Time Verification (C11 _Static_assert):
 * Validates that all 32 token IDs generated by Bison in parser.tab.h
 * match the authoritative values defined in src/lexer/tokens.def.
 * ============================================================================== */
#define TOKEN_DEF(id, val, name) \
    _Static_assert((int)(id) == (val), \
        "Token ID mismatch between parser.tab.h and tokens.def for " name);
#include "tokens.def"
#undef TOKEN_DEF

/* Scanner and Parser Global State */
extern FILE *yyin;
extern int yylineno;
int yylex_destroy(void);

/* Single authoritative definition of syntax error counter */
int syntax_error_count = 0;

int main(int argc, char **argv) {
    const char *source_path = NULL;

    for (int i = 1; i < argc; i++) {
        if (argv[i][0] != '-') {
            source_path = argv[i];
        } else {
            fprintf(stderr, "Usage: %s <source-file>\n", argv[0]);
            return 1;
        }
    }

    if (source_path == NULL) {
        fprintf(stderr, "Usage: %s <source-file>\n", argv[0]);
        return 1;
    }

    FILE *file = fopen(source_path, "r");
    if (!file) {
        fprintf(stderr, "Error: Cannot open source file '%s'\n", source_path);
        return 1;
    }

    /* Initialize scanner and parser state */
    yyin = file;
    yylineno = 1;
    compilecraft_loc_reset();
    lexical_error_count = 0;
    syntax_error_count = 0;

    int parse_status = yyparse();

    fclose(file);
    yylex_destroy();

    if (parse_status == 0 && syntax_error_count == 0 && lexical_error_count == 0) {
        printf("Syntax validation successful.\n");
        return 0;
    }

    return 1;
}
